for (const [scene, primary, secondary, deep, paper, ink, family, label] of rows)
  looks[scene] = { primary, secondary, deep, paper, ink, family, label };
export function slotLook(scene: string): SlotLook {
  return looks[scene] || looks.solar;
}
export function slotThemeVars(scene: string) {
  const v = slotLook(scene);
  return {
    ...slotStageVars(scene),
    "--slot-primary": v.primary,
    "--slot-secondary": v.secondary,
    "--slot-deep": v.deep,
    "--slot-paper": v.paper,
    "--slot-ink": v.ink,
  };
}

